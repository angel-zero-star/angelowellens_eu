#!/usr/bin/env python3
"""Inline a text-only copy of each case study into its root page.

Every page (_site/atlas.html, ...) is an empty shell: the case study lives in
_site/projects/<name>/<name>.html and angelo.js fetches it after load. Anything
that reads the raw HTML without running scripts (AI summarisers, recruiter
tools, link previews) therefore saw no content at all.

This writes a stripped, semantic copy of the fragment (headings, paragraphs,
lists, links, image alt text) into the shell, between the static-copy
markers. A one-line inline script removes it straight away for normal
visitors, so it never shows and never clashes with the IDs and classes of the
copy that folio() loads. No media is kept: the preload scanner would fetch it
before any script could stop it.

Re-run after editing any fragment:  python3 tools/build_static_copy.py
"""
import html
import os
import re
import sys
from html.parser import HTMLParser

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '_site')
START = '<!-- static-copy:start (generated by tools/build_static_copy.py) -->'
END = '<!-- static-copy:end -->'
ANCHOR = '<noscript><p class="caution aligncenter">Enable Javascript to browse this site, please.</p></noscript>'

KEEP = {'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'ul', 'ol', 'li',
        'blockquote', 'figcaption', 'strong', 'em', 'b', 'i', 'a', 'br'}
BLOCK = {'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'ul', 'ol', 'li',
         'blockquote', 'figcaption'}
SKIP = {'head', 'style', 'script', 'noscript', 'svg', 'video', 'audio',
        'iframe', 'canvas', 'template', 'button', 'form', 'select', 'textarea'}
VOID = {'img', 'br', 'hr', 'input', 'meta', 'link', 'source', 'wbr', 'col',
        'area', 'base', 'embed', 'param', 'track'}


class Strip(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []
        self.skip = 0
        self.stack = []   # tags we emitted, so stray closers are ignored

    def handle_starttag(self, tag, attrs):
        if tag in SKIP:
            self.skip += 1
            return
        if self.skip:
            return
        a = dict(attrs)
        if tag == 'img':
            alt = (a.get('alt') or '').strip()
            if len(alt.split()) >= 3:
                self.out.append('<p>%s</p>' % html.escape(alt))
            return
        if tag not in KEEP:
            if tag in ('div', 'section', 'article', 'figure', 'header', 'footer'):
                self.out.append('\n')
            return
        if tag == 'br':
            self.out.append('<br>')
            return
        if tag == 'a':
            href = (a.get('href') or '').strip()
            if not href or href.startswith(('javascript:', '#')):
                self.stack.append('a-')
                return
            self.out.append('<a href="%s">' % html.escape(href, quote=True))
            self.stack.append('a')
            return
        if tag in BLOCK:
            self.out.append('\n')
        self.out.append('<%s>' % tag)
        self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag in SKIP and tag not in VOID:
            self.skip -= 1

    def handle_endtag(self, tag):
        if tag in SKIP:
            self.skip = max(0, self.skip - 1)
            return
        if self.skip or tag not in KEEP or tag == 'br':
            return
        want = 'a' if tag == 'a' else tag
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i] in (want, want + '-'):
                # close anything left open inside it first
                for t in reversed(self.stack[i + 1:]):
                    if not t.endswith('-'):
                        self.out.append('</%s>' % t)
                emitted = not self.stack[i].endswith('-')
                del self.stack[i:]
                if emitted:
                    self.out.append('</%s>' % tag)
                return

    def handle_data(self, data):
        if not self.skip:
            self.out.append(html.escape(re.sub(r'\s+', ' ', data), quote=False))

    def result(self):
        for t in reversed(self.stack):
            if not t.endswith('-'):
                self.out.append('</%s>' % t)
        s = ''.join(self.out)
        # drop elements that ended up empty, then tidy whitespace
        empty = re.compile(r'<(h[1-6]|p|li|ul|ol|blockquote|figcaption|strong|em|b|i)>\s*</\1>')
        prev = None
        while prev != s:
            prev, s = s, empty.sub('', s)
        s = re.sub(r'[ \t]+', ' ', s)
        s = re.sub(r' *\n[\s]*', '\n', s)
        return s.strip()


def build(name):
    frag = os.path.join(ROOT, 'projects', name, name + '.html')
    with open(frag, encoding='utf-8') as f:
        p = Strip()
        p.feed(f.read())
        p.close()
    body = p.result()
    return (START + '\n<div id="static-copy">\n' + body + '\n</div>\n'
            '<script>document.getElementById("static-copy").remove()</script>\n'
            + END)


def main():
    done, skipped = [], []
    for fn in sorted(os.listdir(ROOT)):
        name, ext = os.path.splitext(fn)
        if ext != '.html' or not os.path.isfile(os.path.join(ROOT, 'projects', name, name + '.html')):
            continue
        path = os.path.join(ROOT, fn)
        with open(path, encoding='utf-8') as f:
            page = f.read()
        block = build(name)
        if START in page:
            page = re.sub(re.escape(START) + r'.*?' + re.escape(END),
                          lambda m: block, page, count=1, flags=re.S)
        elif ANCHOR in page:
            page = page.replace(ANCHOR, ANCHOR + '\n' + block, 1)
        else:
            skipped.append(fn)
            continue
        with open(path, 'w', encoding='utf-8') as f:
            f.write(page)
        done.append(fn)
    print('updated %d pages' % len(done))
    if skipped:
        print('no anchor, skipped: ' + ', '.join(skipped), file=sys.stderr)


if __name__ == '__main__':
    main()
